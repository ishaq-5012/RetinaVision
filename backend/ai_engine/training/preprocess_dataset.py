"""Preprocess the raw dataset into backend/dataset/processed/.

Pipeline applied per image (matches inference exactly):
    border removal -> resize 224x224 -> CLAHE -> Gaussian denoise -> RGB

Output layout (mirrors the dataset dir so it can be trained on directly):

    dataset/processed/
        images/
            low/<name>.png
            moderate/<name>.png
            high/<name>.png
        manifest.csv          filename,label,path
        README.md

Train directly on the output with:

    python -m ai_engine.training.train --data-dir dataset/processed --preprocessed

(`--preprocessed` skips re-running the preprocessing step at load time.)

Usage (from backend/):

    python -m ai_engine.training.preprocess_dataset [--data-dir dataset]
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import cv2

from ai_engine.training.config import CLASS_NAMES, DEFAULT_DATA_DIR, LABEL_MAP
from ai_engine.training.dataset_io import load_labels
from ai_engine.training.preprocessing import preprocess_uint8

OUTPUT_SUBDIR = "processed"
TARGET_SIZE = 224
LABEL_KEYS = {idx: key for key, idx in LABEL_MAP.items()}


def preprocess_to_artifacts(data_dir: Path, out_dir: Path, target_size: int = TARGET_SIZE) -> dict:
    """Preprocess all images and write PNGs + manifest into out_dir."""
    out_dir = Path(out_dir)
    images_out = out_dir / "images"
    images_out.mkdir(parents=True, exist_ok=True)

    df = load_labels(data_dir)
    manifest_rows = []
    processed, failed = 0, 0

    for _, row in df.iterrows():
        label_idx = int(row["label"])
        label_name = LABEL_KEYS[label_idx]
        src = Path(row["path"])
        label_out = images_out / label_name
        label_out.mkdir(parents=True, exist_ok=True)
        dst = label_out / f"{src.stem}{src.suffix.lower()}"

        img = cv2.imread(str(src), cv2.IMREAD_COLOR)
        if img is None:
            print(f"  SKIP (unreadable): {src}")
            failed += 1
            continue
        processed_img = preprocess_uint8(img, target_size)
        rgb = cv2.cvtColor(processed_img, cv2.COLOR_BGR2RGB)
        if not cv2.imwrite(str(dst), rgb):
            print(f"  FAIL to write: {dst}")
            failed += 1
            continue
        manifest_rows.append({"filename": dst.name, "label": label_name, "path": str(dst)})
        processed += 1

    (out_dir / "manifest.csv").write_text(
        "filename,label,path\n"
        + "\n".join(f"{r['filename']},{r['label']},{r['path']}" for r in manifest_rows),
        encoding="utf-8",
    )
    (out_dir / "README.md").write_text(
        "# Processed dataset\n\n"
        "Generated by `preprocess_dataset.py`. Images are 224x224 RGB, "
        "border-removed, CLAHE-enhanced and denoised. Normalization (divide by 255)\n"
        "is applied at model input. Train with `--data-dir dataset/processed --preprocessed`.\n",
        encoding="utf-8",
    )

    summary = {
        "source": str(data_dir),
        "output": str(out_dir),
        "processed": processed,
        "failed": failed,
        "per_class": {name: sum(1 for r in manifest_rows if r["label"] == name) for name in CLASS_NAMES},
    }
    (out_dir / "preprocess_report.json").write_text(json.dumps(summary, indent=2), encoding="utf-8")
    return summary


def main() -> None:
    parser = argparse.ArgumentParser(description="Preprocess the dataset into processed images.")
    parser.add_argument("--data-dir", default=str(DEFAULT_DATA_DIR))
    parser.add_argument("--out-dir", default=None, help="Default: <data-dir>/processed")
    parser.add_argument("--size", type=int, default=TARGET_SIZE)
    args = parser.parse_args()

    data_dir = Path(args.data_dir)
    out_dir = Path(args.out_dir) if args.out_dir else (data_dir / OUTPUT_SUBDIR)

    summary = preprocess_to_artifacts(data_dir, out_dir, args.size)
    print(json.dumps(summary, indent=2))
    print(f"Processed dataset -> {out_dir}")


if __name__ == "__main__":
    main()
